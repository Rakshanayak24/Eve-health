import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    Column,
    String,
    Float,
    ForeignKey,
    DateTime,
    Enum as SAEnum,
    UniqueConstraint,
)
from sqlalchemy.orm import relationship

from app.database import Base


def gen_uuid() -> str:
    return str(uuid.uuid4())


class BookingStatus(str, enum.Enum):
    PENDING = "PENDING"
    CONFIRMED = "CONFIRMED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class PaymentStatus(str, enum.Enum):
    PENDING = "PENDING"
    SUCCESS = "SUCCESS"
    FAILED = "FAILED"


class User(Base):
    __tablename__ = "users"

    id = Column(String, primary_key=True, default=gen_uuid)
    email = Column(String, unique=True, nullable=False, index=True)
    full_name = Column(String, nullable=False)
    hashed_password = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    bookings = relationship("Booking", back_populates="user")


class DiagnosticCentre(Base):
    __tablename__ = "diagnostic_centres"

    id = Column(String, primary_key=True, default=gen_uuid)
    name = Column(String, nullable=False, index=True)
    location = Column(String, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    tests = relationship(
        "DiagnosticTest", back_populates="centre", cascade="all, delete-orphan"
    )
    bookings = relationship("Booking", back_populates="centre")


class DiagnosticTest(Base):
    __tablename__ = "diagnostic_tests"

    id = Column(String, primary_key=True, default=gen_uuid)
    centre_id = Column(String, ForeignKey("diagnostic_centres.id"), nullable=False)
    name = Column(String, nullable=False)
    price = Column(Float, nullable=False)
    created_at = Column(DateTime, default=datetime.utcnow)

    centre = relationship("DiagnosticCentre", back_populates="tests")
    bookings = relationship("Booking", back_populates="test")

    __table_args__ = (
        # A centre shouldn't offer the exact same test name twice.
        UniqueConstraint("centre_id", "name", name="uq_test_per_centre"),
    )


class Booking(Base):
    __tablename__ = "bookings"

    id = Column(String, primary_key=True, default=gen_uuid)
    user_id = Column(String, ForeignKey("users.id"), nullable=False, index=True)
    test_id = Column(String, ForeignKey("diagnostic_tests.id"), nullable=False)
    centre_id = Column(String, ForeignKey("diagnostic_centres.id"), nullable=False)

    appointment_time = Column(DateTime, nullable=False)
    amount = Column(Float, nullable=False)
    status = Column(
        SAEnum(BookingStatus, native_enum=False),
        nullable=False,
        default=BookingStatus.PENDING,
        index=True,
    )

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    user = relationship("User", back_populates="bookings")
    test = relationship("DiagnosticTest", back_populates="bookings")
    centre = relationship("DiagnosticCentre", back_populates="bookings")
    payments = relationship("Payment", back_populates="booking")


class Payment(Base):
    """
    A row per payment *attempt*. A booking may accumulate multiple attempts
    (e.g. FAILED then a retried SUCCESS), which keeps a full audit trail
    instead of overwriting history.
    """

    __tablename__ = "payments"

    id = Column(String, primary_key=True, default=gen_uuid)
    booking_id = Column(String, ForeignKey("bookings.id"), nullable=False, index=True)
    amount = Column(Float, nullable=False)
    status = Column(
        SAEnum(PaymentStatus, native_enum=False), nullable=False, default=PaymentStatus.PENDING
    )

    # Unique reference for this attempt, generated by us and echoed back by the
    # (simulated) payment provider in the webhook. This is what we key
    # idempotency off, in addition to the WebhookEvent table below.
    provider_reference = Column(String, unique=True, nullable=False, index=True)

    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    booking = relationship("Booking", back_populates="payments")


class WebhookEvent(Base):
    """
    Records every webhook event we have successfully processed, keyed by the
    provider's event_id. This is the primary idempotency guard for
    POST /payments/webhook/: if an event_id has already been recorded, the
    endpoint short-circuits and returns the original outcome without touching
    booking/payment state again.
    """

    __tablename__ = "webhook_events"

    id = Column(String, primary_key=True, default=gen_uuid)
    event_id = Column(String, unique=True, nullable=False, index=True)
    payment_id = Column(String, ForeignKey("payments.id"), nullable=True)
    payload = Column(String, nullable=True)  # raw payload snapshot, for audit/debug
    created_at = Column(DateTime, default=datetime.utcnow)
